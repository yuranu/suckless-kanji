#!/usr/bin/env node
// Join raw/ sources into web/data/kanji.js (a plain script, so index.html works from file://).
// Output: window.KANJI = [{c, jlpt, freq, grade, strokes, meanings, on, kun, paths, types}, ...]
// ordered by JLPT level (N5 first), then frequency.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const raw = (p) => path.join(root, 'raw', p);

const meta = JSON.parse(fs.readFileSync(raw('kanji-data.json'), 'utf8'));
const svgDir = raw('kanjivg/kanji');

function loadStrokes(ch) {
  const hex = ch.codePointAt(0).toString(16).padStart(5, '0');
  const file = path.join(svgDir, `${hex}.svg`);
  if (!fs.existsSync(file)) return null;
  const svg = fs.readFileSync(file, 'utf8');
  const strokes = [];
  for (const m of svg.matchAll(/<path id="kvg:[0-9a-f]+-s(\d+)"([^>]*?)\sd="([^"]+)"/g)) {
    const type = /kvg:type="([^"]*)"/.exec(m[2]);
    strokes.push({ n: +m[1], d: m[3], type: type ? type[1] : '' });
  }
  strokes.sort((a, b) => a.n - b.n);
  strokes.forEach((s, i) => { if (s.n !== i + 1) throw new Error(`${ch}: stroke numbering gap`); });
  return strokes;
}

const out = [];
const missing = [];
for (const [c, k] of Object.entries(meta)) {
  if (!k.jlpt_new) continue;
  const strokes = loadStrokes(c);
  if (!strokes) { missing.push(c); continue; }
  if (k.strokes && k.strokes !== strokes.length) {
    console.warn(`warn ${c}: KANJIDIC says ${k.strokes} strokes, KanjiVG has ${strokes.length}`);
  }
  out.push({
    c,
    jlpt: k.jlpt_new,
    freq: k.freq ?? null,
    grade: k.grade ?? null,
    strokes: strokes.length,
    meanings: k.meanings,
    on: k.readings_on,
    kun: k.readings_kun,
    paths: strokes.map((s) => s.d),
    types: strokes.map((s) => s.type),
  });
}

out.sort((a, b) => b.jlpt - a.jlpt || (a.freq ?? 1e9) - (b.freq ?? 1e9) || a.c.localeCompare(b.c));

fs.mkdirSync(path.join(root, 'web/data'), { recursive: true });
const header = `// Generated by scripts/build.mjs — do not edit.
// Stroke data: KanjiVG (https://kanjivg.tagaini.net), CC BY-SA 3.0, (C) Ulrich Apel.
// Kanji metadata: KANJIDIC2 (EDRDG, CC BY-SA 4.0) via davidluzgouveia/kanji-data; JLPT levels from tanos.co.uk.
`;
fs.writeFileSync(path.join(root, 'web/data/kanji.js'),
  header + 'window.KANJI = [\n' + out.map((k) => JSON.stringify(k)).join(',\n') + '\n];\n');

const byLevel = {};
for (const k of out) byLevel[`N${k.jlpt}`] = (byLevel[`N${k.jlpt}`] || 0) + 1;
console.log(`wrote ${out.length} kanji`, byLevel);
if (missing.length) console.log(`no KanjiVG data for ${missing.length}: ${missing.join('')}`);
